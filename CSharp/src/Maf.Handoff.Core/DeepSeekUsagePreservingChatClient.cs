using System.Collections.Concurrent;
using System.Runtime.CompilerServices;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using DeepSeek.Agents.AI;
using Microsoft.Extensions.AI;

namespace Maf.Handoff.Core;

/// <summary>
/// Works around DeepSeek.Agents.AI 1.0.4 dropping the provider's final streaming usage chunk.
/// The non-streaming mapper retains ChatResponse.Usage, so adapt that complete response back into
/// framework updates until the upstream streaming mapper accepts DeepSeek's current chunk shape.
/// </summary>
internal sealed class DeepSeekUsagePreservingChatClient(
    IChatClient innerClient, DeepSeekUsageCapture? usageCapture = null, IDisposable? ownedTransport = null) : IChatClient
{
    private readonly ConcurrentDictionary<string, string> _reasoningByCallId = new(StringComparer.Ordinal);
    private readonly ConcurrentDictionary<string, string> _reasoningByMessage = new(StringComparer.Ordinal);

    public async Task<ChatResponse> GetResponseAsync(
        IEnumerable<ChatMessage> messages,
        ChatOptions? options = null,
        CancellationToken cancellationToken = default)
    {
        IReadOnlyList<ChatMessage> history = RestoreReasoning(messages);
        // Handoffs and checkpoint replays can introduce reasoning generated by another client.
        RememberReasoning(history, annotateResponse: false);
        ChatOptions? requestOptions = OptionsForHistory(history, options);
        DeepSeekUsageCapture.CallUsage? call = usageCapture?.BeginCall();
        ChatResponse response = await innerClient.GetResponseAsync(
            history, requestOptions, cancellationToken).ConfigureAwait(false);
        if (call?.Usage is { } usage) response.Usage = usage;
        if (call?.RawUsage is { } rawUsage)
        {
            response.AdditionalProperties ??= [];
            response.AdditionalProperties["provider_usage"] = rawUsage;
        }
        response.ResponseId ??= call?.ResponseId;
        RememberReasoning(response.Messages, annotateResponse: true);
        return response;
    }

    public async IAsyncEnumerable<ChatResponseUpdate> GetStreamingResponseAsync(
        IEnumerable<ChatMessage> messages,
        ChatOptions? options = null,
        [EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        ChatResponse response = await GetResponseAsync(messages, options, cancellationToken).ConfigureAwait(false);
        foreach (ChatResponseUpdate update in response.ToChatResponseUpdates())
        {
            yield return update;
        }
    }

    private IReadOnlyList<ChatMessage> RestoreReasoning(IEnumerable<ChatMessage> messages)
    {
        ChatMessage[] history = [.. messages];
        for (int index = 0; index < history.Length; index++)
        {
            ChatMessage message = history[index];
            if (message.Role != ChatRole.Assistant)
            {
                continue;
            }

            string? reasoning = GetReasoning(message) ?? message.Contents
                .OfType<FunctionCallContent>()
                .Select(call => _reasoningByCallId.GetValueOrDefault(call.CallId))
                .FirstOrDefault(value => !string.IsNullOrWhiteSpace(value));
            if (string.IsNullOrWhiteSpace(reasoning) && message.MessageId is { } messageId)
                reasoning = _reasoningByMessage.GetValueOrDefault("id:" + messageId);
            if (string.IsNullOrWhiteSpace(reasoning) && TextKey(message) is { } textKey)
                reasoning = _reasoningByMessage.GetValueOrDefault(textKey);
            if (string.IsNullOrWhiteSpace(reasoning))
            {
                continue;
            }

            ChatMessage restored = message.Clone();
            restored.Contents = [new TextReasoningContent(reasoning),
                .. message.Contents.Where(content => content is not TextReasoningContent)];
            restored.AdditionalProperties = message.AdditionalProperties is { } properties ? new(properties) : [];
            restored.AdditionalProperties["reasoning_content"] = reasoning;
            history[index] = restored;
        }

        return history;
    }

    private static ChatOptions? OptionsForHistory(IReadOnlyList<ChatMessage> history, ChatOptions? options)
    {
        bool hasToolCalls = history.Any(message => message.Role == ChatRole.Assistant &&
            message.Contents.OfType<FunctionCallContent>().Any());
        if ((options?.Tools is not { Count: > 0 } && !hasToolCalls) ||
            !history.Any(message => message.Role == ChatRole.Assistant && GetReasoning(message) is null))
        {
            return options;
        }

        // Thinking is enabled by default on current DeepSeek models. Missing reasoning from
        // synthetic messages, other providers, or old checkpoints cannot be reconstructed.
        // Final-response requests may remove available tools while retaining earlier tool calls;
        // DeepSeek still validates the reasoning associated with that history.
        // Preserve the complete conversation and tool evidence, but use non-thinking mode
        // for this request rather than inventing reasoning or submitting invalid history.
        ChatOptions projected = options?.Clone() ?? new();
        projected.Reasoning = null;
        projected.AdditionalProperties = options?.AdditionalProperties is { } properties ? new(properties) : [];
        projected.AdditionalProperties[DeepSeekChatOptionKeys.Thinking] = false;
        return projected;
    }

    private void RememberReasoning(IEnumerable<ChatMessage> messages, bool annotateResponse)
    {
        foreach (ChatMessage message in messages.Where(message => message.Role == ChatRole.Assistant))
        {
            string? reasoning = GetReasoning(message);
            if (string.IsNullOrWhiteSpace(reasoning))
            {
                continue;
            }

            if (annotateResponse)
            {
                message.MessageId ??= Guid.NewGuid().ToString("N");
                // Function/text content often survives a framework handoff even when its
                // containing message's metadata, ID and TextReasoningContent do not.
                foreach (AIContent content in message.Contents.Where(content => content is FunctionCallContent or TextContent))
                {
                    content.AdditionalProperties = content.AdditionalProperties is { } properties ? new(properties) : [];
                    content.AdditionalProperties["reasoning_content"] = reasoning;
                }
            }
            if (message.MessageId is { } messageId)
                _reasoningByMessage["id:" + messageId] = reasoning;
            if (TextKey(message) is { } textKey)
            {
                // When IDs are stripped, restore only unambiguous text matches.
                _reasoningByMessage.AddOrUpdate(textKey, reasoning,
                    (_, previous) => previous == reasoning ? previous : string.Empty);
            }

            foreach (FunctionCallContent call in message.Contents.OfType<FunctionCallContent>())
            {
                if (!string.IsNullOrWhiteSpace(call.CallId))
                {
                    _reasoningByCallId[call.CallId] = reasoning;
                }
            }
        }
    }

    private static string? TextKey(ChatMessage message) =>
        !string.IsNullOrWhiteSpace(message.Text) && !message.Contents.OfType<FunctionCallContent>().Any()
            ? "text:" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(message.Text)))
            : null;

    private static string? GetReasoning(ChatMessage message)
    {
        string reasoning = string.Concat(message.Contents.OfType<TextReasoningContent>().Select(content => content.Text));
        if (!string.IsNullOrWhiteSpace(reasoning)) return reasoning;
        return MetadataReasoning(message.AdditionalProperties)
            ?? message.Contents.Select(content => MetadataReasoning(content.AdditionalProperties))
                .FirstOrDefault(value => value is not null)
            ?? NonEmpty((message.RawRepresentation as DeepSeek.Chat.ChatMessage)?.ReasoningContent);
    }

    private static string? MetadataReasoning(AdditionalPropertiesDictionary? properties) =>
        properties?.TryGetValue("reasoning_content", out object? value) is true
            ? value switch
            {
                string text => NonEmpty(text),
                JsonElement { ValueKind: JsonValueKind.String } json => NonEmpty(json.GetString()),
                _ => null,
            }
            : null;

    private static string? NonEmpty(string? value) => string.IsNullOrWhiteSpace(value) ? null : value;

    public object? GetService(Type serviceType, object? serviceKey = null) =>
        serviceType.IsInstanceOfType(this) ? this : innerClient.GetService(serviceType, serviceKey);

    public void Dispose()
    {
        // The decorator does not own the provider client.
        ownedTransport?.Dispose();
    }
}
